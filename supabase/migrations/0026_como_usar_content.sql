## O básico

Este é o portfólio pessoal de Felipe Zanoni da Rosa: projetos, artigos técnicos, currículo e contato — tudo num só lugar, em português e inglês.

No canto superior direito tem um ícone de engrenagem com três ajustes: tema claro/escuro, reduzir animações (pra quem prefere menos movimento na tela) e o seletor PT/EN. Suas escolhas ficam guardadas num cookie e valem pra próxima visita.

## Busca

Aperte **Ctrl+K** (ou **⌘K** no Mac) em qualquer página pra abrir a busca rápida. Ela entende linguagem natural — não precisa acertar o termo exato, só descrever o que você procura (ex. "projeto que usa banco de dados" encontra algo que só menciona "Supabase" no texto). Também tem uma versão embutida na home e uma página dedicada em [/busca](/pt/busca). Com o campo vazio, a busca mostra as tecnologias mais usadas nos projetos, cada uma com a % de uso.

