## The basics

This is the personal portfolio of Felipe Zanoni da Rosa: projects, technical articles, resume and contact — all in one place, in Portuguese and English.

In the top-right corner there's a gear icon with three settings: light/dark theme, reduce animations (for anyone who prefers less motion on screen), and the PT/EN switch. Your choices are saved in a cookie and carry over to your next visit.

## Search

Press **Ctrl+K** (or **⌘K** on Mac) on any page to open quick search. It understands natural language — you don't need the exact term, just describe what you're looking for (e.g. "project that uses a database" finds something that only mentions "Supabase" in its text). There's also a version embedded on the home page and a dedicated [/busca](/en/busca) page. With an empty query, search shows the most-used technologies across projects, each with its usage %.

## Pages

- **About**: my background and what drives me.
- **Services**: what I offer as a developer.
- **Projects**: each card shows technologies, company/context and a link to the repo or live site. You can search by name/technology/company/author and filter by technology — filters are saved in the URL, so you can share an already-filtered link.
- **Articles**: technical writing (when this section is active).
- **Contact**: a direct form — name, email and message land in my inbox.
- **Resume**: experience, education and skills.
- **[/status](/en/status)**: the site's technical internals — current deploy, real database latency, how many projects/articles/technologies are on record. Everything read live, nothing simulated.

## Export for AI

The "export for AI" link in the footer generates JSON with projects, resume and contact details — meant to be pasted straight into a prompt if you want an AI to answer questions about my work.

